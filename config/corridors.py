def get_corridor_geo(segment_id: str) -> Optional[Dict[str, Any]]:
    """Retrieves verified geographic and operational metadata for a road segment."""
    return NAGPUR_CORRIDORS_GEO.get(segment_id)


def get_approved_corridors() -> List[str]:
    """Returns list of corridor IDs verified and approved for automated ingestion."""
    return [
        cid for cid, c in NAGPUR_CORRIDORS_GEO.items()
        if c.get("approved_for_ingestion", False)
    ]
